package nl.brul.api.features.report.repository

import java.nio.file.Files
import java.nio.file.Path
import java.util.concurrent.ConcurrentHashMap

/**
 * Where the bytes of photos are kept. The database only stores the key.
 *
 * Behind an interface so the service does not care whether photos live on
 * disk or (in tests) in memory.
 */
interface PhotoStorage {
    fun save(key: String, bytes: ByteArray)

    fun load(key: String): ByteArray?

    fun delete(key: String)
}

/** Stores each photo as a file in [root] (default: ./uploads). */
class FileSystemPhotoStorage(
    private val root: Path
) : PhotoStorage {

    override fun save(key: String, bytes: ByteArray) {
        Files.createDirectories(root)
        Files.write(resolve(key), bytes)
    }

    override fun load(key: String): ByteArray? {
        val file = resolve(key)
        return if (Files.exists(file)) Files.readAllBytes(file) else null
    }

    override fun delete(key: String) {
        Files.deleteIfExists(resolve(key))
    }

    // Keys are generated by the service, but we still refuse anything
    // that could point outside the uploads folder.
    private fun resolve(key: String): Path {
        require(key.matches(Regex("[A-Za-z0-9._-]+"))) {
            "Invalid storage key."
        }

        return root.resolve(key)
    }
}

/** Keeps photos in memory. Used in tests and handy for experiments. */
class InMemoryPhotoStorage : PhotoStorage {

    private val files = ConcurrentHashMap<String, ByteArray>()

    val keys: Set<String>
        get() = files.keys.toSet()

    override fun save(key: String, bytes: ByteArray) {
        files[key] = bytes.copyOf()
    }

    override fun load(key: String): ByteArray? = files[key]?.copyOf()

    override fun delete(key: String) {
        files.remove(key)
    }
}
